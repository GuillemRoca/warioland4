#!/usr/bin/env python3
"""Rasterise the lettering of the epilogue's steak flyer into lib/flyer_masks.py.

Only needed when the flyer text in graphics_ca.toml changes.  Requires Pillow
and the Inter font (https://rsms.me/inter/, SIL Open Font License); the build
itself only reads the generated ASCII-art masks.

usage: python3 tools/make_flyer_masks.py "BISTECS!" "Menja'n a dojo!!" [--fonts DIR]
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# (font file, pixel size, italic shear) for the headline and the second line
STYLES = [("Inter-Black.otf", 28, 0.25), ("Inter-ExtraBold.otf", 18, 0.2)]


def mask_text(text, font_path, size, shear):
    f = ImageFont.truetype(font_path, size)
    l, t, r, b = f.getbbox(text)
    im = Image.new("L", (r - l + 40, b - t + 10), 0)
    ImageDraw.Draw(im).text((10 - l, 5 - t), text, font=f, fill=255)
    h = im.height
    im = im.transform((im.width + int(h * shear) + 4, h), Image.AFFINE,
                      (1, shear, -h * shear, 0, 1, 0), Image.BILINEAR)
    m = [[1 if im.getpixel((x, y)) > 110 else 0 for x in range(im.width)] for y in range(im.height)]
    ys = [y for y in range(len(m)) if any(m[y])]
    xs = [x for x in range(len(m[0])) if any(m[y][x] for y in ys)]
    return ["".join("#" if v else "." for v in row[xs[0]:xs[-1] + 1]) for row in m[ys[0]:ys[-1] + 1]]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("lines", nargs=2)
    ap.add_argument("--fonts", default="/usr/share/fonts/opentype/inter")
    a = ap.parse_args()
    out = ['"""Generated by tools/make_flyer_masks.py: lettering of the steak flyer."""', "", "MASKS = {"]
    for text, (font, size, shear) in zip(a.lines, STYLES):
        rows = mask_text(text, os.path.join(a.fonts, font), size, shear)
        out.append(f"    {text!r}: \"\"\"")
        out += rows
        out.append('""",')
    out.append("}")
    with open(os.path.join(HERE, "lib", "flyer_masks.py"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
