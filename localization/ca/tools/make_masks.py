#!/usr/bin/env python3
"""Rasterise pre-drawn lettering into lib/art_masks.py.

Only needed when one of the texts below changes (they must match
graphics_ca.toml).  Requires Pillow and the Inter font
(https://rsms.me/inter/, SIL Open Font License); the build itself only reads
the generated ASCII-art masks.

usage: python3 tools/make_masks.py [--fonts DIR]
"""
import argparse
import os
import tomllib

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# group -> [(font file, pixel size, italic shear, horizontal scale[, letter spacing])] per line
STYLES = {
    "steak_flyer": [("Inter-Black.otf", 28, 0.25, 1.0), ("Inter-ExtraBold.otf", 18, 0.2, 1.0)],
    "board_burst": [("Inter-Black.otf", 19, 0.0, 0.76), ("Inter-Black.otf", 9, 0.0, 1.0),
                    ("Inter-Black.otf", 16, 0.0, 0.66)],
    "steak_price": [("Inter-Black.otf", 40, 0.12, 0.9)],
    # graffiti: letters drawn one by one, tilted and bouncing, with extra spacing
    "pinball_sfx": [("Inter-Black.otf", 21, 0.0, 0.7, 4), ("Inter-Black.otf", 26, 0.0, 0.7, 2),
                    ("Inter-Black.otf", 19, 0.0, 0.8, 2)],
}
BOUNCE = [0, -2, 1, -1, 2, -2, 1, 0, -1, 1]
TILT = [4, -5, 3, -4, 5, -3, 4, -4, 3, -5]


def mask_graffiti(text, font_path, size, xscale, track):
    f = ImageFont.truetype(font_path, size)
    pieces = []
    for i, ch in enumerate(text):
        l, t, r, b = f.getbbox(ch)
        im = Image.new("L", (r - l + 12, size + 12), 0)
        ImageDraw.Draw(im).text((6 - l, 6), ch, font=f, fill=255)
        im = im.rotate(TILT[i % len(TILT)], resample=Image.BILINEAR, expand=False)
        pieces.append(im.resize((max(1, int(im.width * xscale)), im.height), Image.BILINEAR))
    canvas = Image.new("L", (sum(p.width for p in pieces) + track * len(pieces), size + 20), 0)
    x = 0
    for i, p in enumerate(pieces):
        canvas.paste(p, (x, 4 + BOUNCE[i % len(BOUNCE)]), p)
        x = int(x + p.width - 12 * xscale + track)
    m = [[1 if canvas.getpixel((x, y)) > 110 else 0 for x in range(canvas.width)] for y in range(canvas.height)]
    ys = [y for y in range(len(m)) if any(m[y])]
    xs = [x for x in range(len(m[0])) if any(m[y][x] for y in ys)]
    return ["".join("#" if v else "." for v in row[xs[0]:xs[-1] + 1]) for row in m[ys[0]:ys[-1] + 1]]


def mask_text(text, font_path, size, shear, xscale):
    f = ImageFont.truetype(font_path, size)
    l, t, r, b = f.getbbox(text)
    im = Image.new("L", (r - l + 40, b - t + 10), 0)
    ImageDraw.Draw(im).text((10 - l, 5 - t), text, font=f, fill=255)
    h = im.height
    if shear:
        im = im.transform((im.width + int(h * shear) + 4, h), Image.AFFINE,
                          (1, shear, -h * shear, 0, 1, 0), Image.BILINEAR)
    if xscale != 1.0:
        im = im.resize((max(1, int(im.width * xscale)), h), Image.BILINEAR)
    m = [[1 if im.getpixel((x, y)) > 110 else 0 for x in range(im.width)] for y in range(im.height)]
    ys = [y for y in range(len(m)) if any(m[y])]
    xs = [x for x in range(len(m[0])) if any(m[y][x] for y in ys)]
    return ["".join("#" if v else "." for v in row[xs[0]:xs[-1] + 1]) for row in m[ys[0]:ys[-1] + 1]]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fonts", default="/usr/share/fonts/opentype/inter")
    a = ap.parse_args()
    with open(os.path.join(HERE, "graphics_ca.toml"), "rb") as f:
        texts = tomllib.load(f)
    out = ['"""Generated by tools/make_masks.py: pre-rasterised lettering."""', "", "MASKS = {"]
    for group, styles in STYLES.items():
        for text, (font, size, shear, xscale, *track) in zip(texts[group], styles):
            if track:
                rows = mask_graffiti(text, os.path.join(a.fonts, font), size, xscale, track[0])
            else:
                rows = mask_text(text, os.path.join(a.fonts, font), size, shear, xscale)
            out.append(f"    ({group!r}, {text!r}): \"\"\"")
            out += rows
            out.append('""",')
    out.append("}")
    with open(os.path.join(HERE, "lib", "art_masks.py"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
